"""
Dependency-free streaming reader for the LANL "cyber1" .txt.gz files.

Why this exists
----------------
The auth.txt.gz file is 7.2 GB. Downloading it is unnecessary for every
experiment in this project except the one full-dataset paper run, and the
user explicitly does not want it sitting on disk. This module reads the
remote gzip stream directly, decompressing as bytes arrive, and lets the
caller stop as soon as it has read past its time window -- so a 30-day
window transfers only the fraction of the file up to that point, not all
7.2 GB.

The credential problem
-----------------------
The download links on https://csr.lanl.gov/data/cyber1/ are signed,
time-limited URLs of the form::

    https://csr.lanl.gov/data-fence/<expiry>/<signature>/cyber1/<file>.txt.gz

`<expiry>`/`<signature>` are generated by that page *after you submit the
registration form there* -- they are not static HTML on the page, so this
module cannot "scrape a fresh link" automatically (we checked: the page
served to an unauthenticated fetch contains the filenames and sizes but no
anchor tags or embedded links at all). Concretely this means:

    1. The signed link is a bearer credential. It is read at *run time*
       from the LMSAFE_LANL_BASE_URL environment variable, or interactively
       via getpass if none is set. It is never written into a config file,
       never logged, and never appears in a stack trace (see
       `resolve_base_url` and the try/except around every HTTP error
       below).
    2. When a link expires (they are valid for a few hours), re-visit the
       LANL page, resubmit the form, and export the new link. There is no
       way around this short of LANL changing how the page issues links.

Everything else in this module is adapted, with only cosmetic changes,
from a standalone script that was already round-trip tested against a
local fake range-capable HTTP server (including a forced mid-stream
connection drop, verified by a mutation test to actually change the
output if the completeness check is removed). The gzip-trailer
completeness check in `iter_lines` below is the one genuinely subtle
piece of this module: `http.client`'s `read()` can return an empty chunk
on a dropped connection *without* raising, which would otherwise look
exactly like a clean end-of-file and silently truncate the data with no
error at all.
"""
from __future__ import annotations

import getpass
import http.client
import os
import sys
import time
import urllib.error
import urllib.request
import zlib
from typing import Iterator

UA = "Mozilla/5.0 (research-data-stream; lmsafe)"
FILE_NAMES = ("auth", "proc", "flows", "dns", "redteam")

ENV_VAR = "LMSAFE_LANL_BASE_URL"

EXPIRED_MSG = (
    "the LANL signed link is expired or invalid. Re-open "
    "https://csr.lanl.gov/data/cyber1/, resubmit the registration form to "
    "get a fresh signed link, then set {env} (or paste it when prompted) "
    "and re-run."
).format(env=ENV_VAR)


def resolve_base_url(interactive: bool = True) -> str:
    """Return the base URL (without a trailing filename) for the signed
    LANL link, read at run time -- never hardcoded, never persisted.

    Resolution order:
        1. The `LMSAFE_LANL_BASE_URL` environment variable.
        2. If `interactive` and stdin is a TTY (e.g. an interactive Colab
           cell): prompt with `getpass`, so the pasted link does not echo
           to the notebook output or get captured in cell history.

    We deliberately do *not* attempt to fetch
    https://csr.lanl.gov/data/cyber1/ and parse a link out of it: the
    signed link is only generated after a registration form is submitted
    server-side, so a plain page fetch has nothing to parse (see module
    docstring). Automating that form submission is out of scope here --
    it would mean scripting a third-party site's registration flow, and
    we have no way to test that against the live site from this sandbox.
    """
    raw = os.environ.get(ENV_VAR, "")
    if not raw and interactive and sys.stdin.isatty():
        raw = getpass.getpass(
            "Paste the LANL signed link (input hidden, not logged): "
        )
    if not raw:
        raise RuntimeError(
            f"Set {ENV_VAR} to the signed link from "
            "https://csr.lanl.gov/data/cyber1/ and re-run."
        )
    raw = raw.strip()
    if raw.endswith(".txt.gz"):
        raw = raw.rsplit("/", 1)[0]
    return raw.rstrip("/") + "/"


def file_url(base_url: str, name: str) -> str:
    """Build the full URL for one of the five cyber1 files."""
    if name not in FILE_NAMES:
        raise ValueError(f"unknown LANL file {name!r}, expected one of {FILE_NAMES}")
    return f"{base_url}{name}.txt.gz"


def redact(url: str) -> str:
    """Return a safe-to-print version of a signed URL (credential redacted).

    Used everywhere this module might otherwise print/log/raise an
    exception that embeds the URL -- a signed link printed into a shared
    notebook or an error-tracking system is a leaked credential.
    """
    try:
        head, _, tail = url.partition("/cyber1/")
        return f"https://csr.lanl.gov/data-fence/<redacted>/cyber1/{tail}" if tail else "<redacted>"
    except Exception:
        return "<redacted>"


def iter_lines(url: str, retries: int = 10) -> Iterator[bytes]:
    """Yield decompressed lines (bytes, no trailing newline) from a remote
    .gz file, streaming -- never buffering the whole file in memory.

    Robustness properties (each one earned from an earlier bug):

    * **Reconnect-and-resume.** If the connection drops partway through,
      we reopen the request and skip lines already yielded, so the
      caller sees one seamless stream and never double-counts a line.
    * **Silent-truncation guard.** `http.client.HTTPResponse.read()` can
      return `b""` when the server simply closes the socket early --
      this looks identical to a clean EOF and raises nothing. The only
      reliable signal is the gzip trailer: `zlib.decompressobj` sets
      `.eof` only after it has consumed a complete member including its
      trailing CRC32/size footer. We check `dec.eof` after the read loop
      exits and raise if it is False, which turns a silent data-loss bug
      into a retried connection. A mutation test
      (tests/test_lanl_stream_mutant.py-equivalent) confirms that without
      this check, a mid-stream drop silently returns a truncated-but-
      well-formed-looking line stream.
    * **Concatenated gzip members.** Some LANL mirrors serve
      multi-member gzip files; we loop re-initializing the decompressor
      on `dec.unused_data` so no trailing member is dropped.
    * **Credential-safe errors.** 401/403/410 (expired/invalid signed
      link) raise `LinkExpiredError` with no URL in the message, so a
      stack trace pasted into a bug report never leaks the token.

    Parameters
    ----------
    url : str
        Full URL to one `<file>.txt.gz`.
    retries : int
        Max reconnect attempts before giving up.
    """
    yielded = 0
    attempt = 0
    while True:
        seen = 0
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with urllib.request.urlopen(req, timeout=120) as r:
                dec = zlib.decompressobj(16 + zlib.MAX_WBITS)
                buf = b""
                while True:
                    chunk = r.read(1 << 20)
                    if not chunk:
                        break
                    data = dec.decompress(chunk)
                    while dec.eof and dec.unused_data:  # concatenated gzip members
                        rest = dec.unused_data
                        dec = zlib.decompressobj(16 + zlib.MAX_WBITS)
                        data += dec.decompress(rest)
                    buf += data
                    *lines, buf = buf.split(b"\n")
                    for ln in lines:
                        seen += 1
                        if seen > yielded:
                            yielded += 1
                            yield ln
                if not dec.eof:
                    # Connection died mid-file; http.client did not raise.
                    raise OSError("stream ended early (incomplete gzip member)")
                if buf:
                    seen += 1
                    if seen > yielded:
                        yielded += 1
                        yield buf
                return
        except urllib.error.HTTPError as e:
            if e.code in (401, 403, 410):
                raise LinkExpiredError(EXPIRED_MSG) from None
            err = f"HTTP {e.code}"
        except (OSError, http.client.HTTPException, zlib.error) as e:
            err = type(e).__name__
        attempt += 1
        if attempt > retries:
            raise RuntimeError(f"giving up after {retries} reconnects ({err})")
        print(
            f"[lanl_stream] connection problem ({err}); reconnect "
            f"{attempt}/{retries}, resuming after {yielded:,} lines",
            file=sys.stderr,
            flush=True,
        )
        time.sleep(min(30, 2 * attempt))


class LinkExpiredError(RuntimeError):
    """Raised when the signed LANL link is rejected (401/403/410)."""
